#!/usr/bin/env python3
"""Перепись сообщений 16 коммитов DaroSite на лаконичный стиль.

stdin: старое сообщение; stdout: новое. Совпадение по началу темы;
если префикс не найден, сообщение остаётся как есть.
"""
import sys

MAP = [
    ("метафайл: AGENTS — ядро п.6", "Запретить прямые удаления"),
    ("метафайл: инцидент прод-деплоя закрыт", "Закрыть инцидент прод-деплоя"),
    ("метафайл: SESSIONS — уточнение заказчика", "Уточнить журналы после отката"),
    ("метафайл: README — раздел «Кому это надо»", "Перенести ответ в README"),
    ("контент: секция «Кому это надо» снята", "Убрать секцию со страницы об авторе"),
    ("метафайл: SESSIONS — итоги чанка", "Записать итоги чанка"),
    ("контент: об авторе — секция «Кому это надо»", "Добавить секцию «Кому это надо»"),
    ("метафайл: зафиксирован принцип", "Зафиксировать принцип авторского сайта"),
    ("метафайл: чанк CI закрыт", "Отметить деплой в бэклоге"),
    ("инфра: OFL.txt", "Нормализовать OFL.txt"),
    ("метафайл: SESSIONS — журнал сессии", "Записать журнал сессии"),
    ("метафайл: no-traces.md привязан", "Привязать no-traces к репо"),
    ("инфра: CI-воркфлоу", "Добавить деплой на Pages"),
    ("скрипт: два гейта", "Добавить проверки ссылок и слопа"),
    ("инфра: правила проекта", "Добавить правила проекта"),
    ("метафайл: паспорт репо и бэклог", "Добавить паспорт репо и бэклог"),
]

msg = sys.stdin.read()
for prefix, new in MAP:
    if msg.startswith(prefix):
        print(new)
        sys.exit(0)
sys.stdout.write(msg)
