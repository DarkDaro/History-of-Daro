export interface DossierFile {
  id: string;
  name: string;
  tag: string;
  role: string;
  status: string;
  /** 0–10 — шкала из подписи threatLabel. */
  threat: number;
  threatLabel: string;
  assets: string[];
  log: { speaker: string; text: string };
  text: string;
  accent: Accent;
}

/** Корпоративный файл досье: базовый текст берётся из CORPORATIONS. */
function corpFile(
  id: string,
  status: string,
  threat: number,
  threatLabel: string,
  assets: string[],
  log: { speaker: string; text: string },
): DossierFile {
  const corp = CORPORATIONS.find((c) => c.id === id)!;
  return {
    id: `HMD-${corp.id}`,
    name: corp.name,
    tag: corp.tag,
    role: corp.role,
    status,
    threat,
    threatLabel,
    assets,
    log,
    text: corp.text,
    accent: corp.accent,
  };
}

