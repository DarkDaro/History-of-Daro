import { type Accent } from "./shared";

export interface GlossaryEntry {
  /** Якорь карточки: /glossary#<id> (латиница, без пробелов). */
  id: string;
  term: string;
  /** Подпись под термином: тип записи, статус в каноне. */
  kind?: string;
  /** Дополнительные ключи поиска: синонимы, коды, имена. */
  aliases?: string[];
  /** Определение — словарь автора v1.0, редакция под голос сайта. */
  text: string;
  accent: Accent;
  /** Где на сайте тема раскрыта подробнее (опционально). */
  href?: string;
  hrefLabel?: string;
  /** Вторая связка (опционально): например, объект на карте города — /map. */
  also?: { href: string; label: string };
}

